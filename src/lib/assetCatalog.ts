import { mm } from '@/model/units';
import type { Size3D } from '@/model/geometry';

export interface AssetEntry {
  /** Stable id used as `InventoryItem.assetRef`. Matches the SIS item number. */
  id: string;
  /** Display name from the SIS catalog. */
  name: string;
  /** Catalog section. */
  category: AssetCategory;
  /** Procedurally generated 3D model, loaded by the Three.js view. */
  glbUrl: string;
  /** Original CAD file under /public, when we have one. */
  stepUrl?: string;
  /** Bounding-box dimensions in mm (W × D × H) from the SIS catalog. */
  size: Size3D;
  /** Short note shown in the library card. */
  note?: string;
}

export type AssetCategory =
  | 'Wall Units'
  | 'Racks'
  | 'Podiums'
  | 'Tables'
  | 'Accessories'
  | 'Logos'
  | 'Mannequins'
  | 'Carpets';

export const ASSET_CATEGORIES: readonly AssetCategory[] = [
  'Wall Units',
  'Racks',
  'Podiums',
  'Tables',
  'Accessories',
  'Logos',
  'Mannequins',
  'Carpets',
] as const;

const size = (w: number, d: number, h: number): Size3D => ({
  width: mm(w),
  depth: mm(d),
  height: mm(h),
});

const glb = (id: string) => `/assets/3d/${id}.glb`;

function entry(
  id: string,
  name: string,
  category: AssetCategory,
  w: number,
  d: number,
  h: number,
  extra?: Partial<AssetEntry>,
): AssetEntry {
  return { id, name, category, glbUrl: glb(id), size: size(w, d, h), ...extra };
}


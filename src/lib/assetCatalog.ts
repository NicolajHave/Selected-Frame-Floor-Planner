/** assetRefs written by earlier versions of the planner. */
const LEGACY_IDS: Record<string, string> = {
  '105-06-001-E': '105-06-001',
  '105-09-002-A': '105-09-002',
  '105-17-007-01-A': '105-17-007',
};

export function findAsset(id: string | undefined): AssetEntry | undefined {
  if (!id) return undefined;
  const resolved = LEGACY_IDS[id] ?? id;
  return ASSET_CATALOG.find((a) => a.id === resolved);
}
